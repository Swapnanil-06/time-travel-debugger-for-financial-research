"""Embed the verified public CSV for the Worker's read-only Python filesystem.

This generated module is ignored. The CSV and provenance JSON remain the source
of truth and are checked before any deploy bundle is produced.
"""
import hashlib
import json
import shutil
import subprocess
import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main():
    raw = (ROOT / "data/dgs10.csv").read_bytes()
    provenance = json.loads((ROOT / "data/provenance.json").read_text("utf-8"))
    if hashlib.sha256(raw).hexdigest() != provenance["raw_csv_sha256"]:
        raise SystemExit("Dataset checksum failed; refusing to bundle modified source data.")
    target = ROOT / "build/worker"
    package = target / "app"
    package.mkdir(parents=True, exist_ok=True)
    # An explicit module root prevents Wrangler from recursively attaching tests,
    # build artifacts and node_modules to the Python deployment.
    for name in ("__init__.py", "engine.py", "store.py", "model_v1.py", "model_v2.py", "cloud_store.py", "cloud_api.py"):
        shutil.copyfile(ROOT / "app" / name, package / name)
    shutil.copyfile(ROOT / "worker.py", target / "worker.py")
    generated = package / "_cloud_data.py"
    generated.write_text(
        '"""Generated by scripts/prepare_worker.py; do not edit."""\n'
        + "CSV_BYTES = " + repr(raw) + "\n"
        + "PROVENANCE = " + repr(provenance) + "\n",
        encoding="utf-8", newline="\n",
    )
    vendor = ROOT / "python_modules"
    required = "1.9.6"
    installed = {dist.metadata["Name"]: dist.version for dist in metadata.distributions(path=[str(vendor)])}
    if installed.get("workers-runtime-sdk") != required:
        subprocess.run([
            sys.executable, "-m", "pip", "install", "--target", str(vendor),
            "--upgrade", "--no-compile", "--requirement", str(ROOT / "requirements-cloudflare.txt"),
        ], check=True)
    print("Verified data, prepared isolated Worker modules and bundled the pinned runtime SDK.")


if __name__ == "__main__":
    main()
